def sample_font(path, *, cff=False):
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen
    from fontTools.pens.t2CharStringPen import T2CharStringPen

    builder = FontBuilder(1000, isTTF=not cff)
    names = [".notdef", "A", "ga"]
    builder.setupGlyphOrder(names)
    builder.setupCharacterMap({65: "A", 0xAC00: "ga"})
    glyphs = {}
    for name in names:
        pen = T2CharStringPen(600, None) if cff else TTGlyphPen(None)
        pen.moveTo((50, 0))
        pen.lineTo((300, 700))
        pen.lineTo((550, 0))
        pen.closePath()
        glyphs[name] = pen.getCharString() if cff else pen.glyph()
    if cff:
        builder.setupCFF(
            "MagicStage7",
            {
                "FullName": "Magic Stage 7",
                "FamilyName": "Magic Stage 7",
                "Weight": "Regular",
            },
            glyphs,
            {},
        )
    else:
        builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics({name: (600, 50) for name in names})
    builder.setupHorizontalHeader(ascent=800, descent=-200)
    builder.setupNameTable(
        {
            "familyName": "Magic Stage 7",
            "styleName": "Regular",
            "uniqueFontIdentifier": "Magic Stage 7 Test",
            "fullName": "Magic Stage 7",
            "psName": "MagicStage7",
            "version": "Version 1.0",
            "licenseDescription": "Synthetic verification font generated by magic_converter; no third-party font data.",
        }
    )
    builder.setupOS2(
        sTypoAscender=800,
        sTypoDescender=-200,
        usWinAscent=800,
        usWinDescent=200,
        fsType=2,
    )
    builder.setupPost()
    if not cff:
        builder.setupFvar([("wght", 100, 400, 900, "Weight")], [])
    builder.save(path)


def check_specialized(root):
    import sys
    import hashlib

    bundle = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parents[3]))
    licenses = bundle / "licenses" / "stage7"
    entries = json.loads((licenses / "manifest.json").read_text(encoding="utf-8"))
    if len(entries) != 7 or any(
        hashlib.sha256((licenses / e["file"]).read_bytes()).hexdigest() != e["sha256"]
        for e in entries
    ):
        raise RuntimeError("Stage-7 upstream license texts are missing or changed")
    from magic_converter.core.conversion.builtin_converters import create_catalog
    from magic_converter.core.conversion.conversion_request import prepare_request
    from magic_converter.core.conversion.conversion_execution import execute_file
    from magic_converter.core.specialized.ebook_converter import Book, Chapter, write_epub, read_book
    from magic_converter.core.specialized.safe_html import image_uri
    from magic_converter.core.specialized.font_converter import signature
    from fontTools.ttLib import TTFont
    from magic_converter.core.specialized.geo_converter import read_geo
    from magic_converter.core.specialized.mesh_converter import read_mesh

    folder = root / "specialized"
    folder.mkdir(exist_ok=True)
    catalog = create_catalog()
    notices = []

    def run(source, key):
        request = prepare_request([source], key, catalog)
        return execute_file(
            request, request.files[0], None, lambda _: None, notices.append
        )

    value = {
        "title": "한글 자료",
        "integer": 9007199254740993,
        "nested": [True, None, {"x": 1.25}],
    }
    source = folder / "sample.json"
    source.write_text(json.dumps(value, ensure_ascii=False), encoding="utf-8")
    yaml = run(source, "data:yaml")
    back = run(yaml, "data:json")
    if json.loads(back.read_text(encoding="utf-8")) != value:
        raise RuntimeError("Typed data roundtrip failed")
    font = folder / "synthetic.ttf"
    sample_font(font)
    with TTFont(font) as original:
        expected = signature(original)
    for target in ("woff", "woff2", "otf"):
        converted = run(font, "font:" + target)
        with TTFont(converted) as checked:
            if signature(checked) != expected:
                raise RuntimeError("Font cmap/tables/variation/fsType roundtrip failed")
    image = io.BytesIO()
    Image.new("RGB", (31, 19), (11, 120, 230)).save(image, format="PNG")
    uri = image_uri(image.getvalue())
    epub = folder / "two chapters.epub"
    write_epub(
        Book(
            "한글 책",
            ["홍길동"],
            "ko",
            "설명",
            "출판사",
            [
                Chapter("첫 장", f'<p><strong>Alpha</strong><img src="{uri}"/></p>'),
                Chapter("둘째 장", "<p>Beta</p><table><tr><td>42</td></tr></table>"),
            ],
            uri,
        ),
        epub,
    )
    fb2 = run(epub, "ebook:fb2")
    restored = run(fb2, "document:epub")
    book = read_book(restored, "epub")
    from bs4 import BeautifulSoup
    picture = BeautifulSoup(book.chapters[0].body, "html.parser").find("img")
    if (
        book.title != "한글 책"
        or book.authors != ["홍길동"]
        or len(book.chapters) != 2
        or "Beta" not in book.chapters[1].body
        or picture is None
        or book.assets.resolve(picture["src"])[0] != image.getvalue()
        or book.assets.resolve(book.cover)[0] != image.getvalue()
    ):
        raise RuntimeError("Book metadata/chapter/image preservation failed")
    docx = run(epub, "document:docx")
    from docx import Document

    doc = Document(docx)
    if len(doc.tables) != 1 or len(doc.inline_shapes) != 1:
        raise RuntimeError("Book table/picture DOCX structure failed")
    eml = folder / "mail.eml"
    mail = EmailMessage()
    mail["Subject"] = "한글 제목"
    mail["From"] = "sender@example.test"
    mail["To"] = "recipient@example.test"
    mail.set_content("본문", charset="euc-kr")
    mail.add_alternative(
        '<p>본문<img src="cid:logo"/><img src="https://example.test/tracker"/></p><script>bad()</script>',
        subtype="html",
        charset="utf-8",
    )
    mail.get_payload()[-1].add_related(
        image.getvalue(), maintype="image", subtype="png", cid="<logo>"
    )
    mail.add_attachment(
        b"\x00\xffattachment",
        maintype="application",
        subtype="octet-stream",
        filename="../../한글.bin",
    )
    raw = mail.as_bytes(policy=policy.SMTP)
    eml.write_bytes(raw)
    exported = run(eml, "document:html").read_text(encoding="utf-8")
    if (
        "한글 제목" not in exported
        or uri not in exported
        or "<script" in exported
        or "https://example.test/tracker" in exported
    ):
        raise RuntimeError("Mail charset/CID/sanitization failed")
    archive = run(eml, "email:attachments")
    with zipfile.ZipFile(archive) as z:
        entries = json.loads(z.read("manifest.json"))["attachments"]
        binary = next(e for e in entries if e["original_name"] == "../../한글.bin")
        if (
            z.read("original.eml") != raw
            or z.read(binary["path"]) != b"\x00\xffattachment"
        ):
            raise RuntimeError("Mail original/attachment bytes changed")
    obj = folder / "triangle.obj"
    obj.write_text("v 0 0 0\nv 2 0 0\nv 0 3 0\nf 1 2 3\n", encoding="ascii")
    stl = run(obj, "mesh:stl")
    ply = run(stl, "mesh:ply")
    mesh = read_mesh(ply, "ply")
    if len(mesh.faces) != 1 or mesh.vertices != [
        (0.0, 0.0, 0.0),
        (2.0, 0.0, 0.0),
        (0.0, 3.0, 0.0),
    ]:
        raise RuntimeError("Mesh topology/coordinates failed")
    geo = folder / "point.geojson"
    geo.write_text(
        json.dumps(
            {
                "type": "Feature",
                "properties": {"name": "서울", "n": 42},
                "geometry": {"type": "Point", "coordinates": [126.978, 37.5665, 12]},
            }
        ),
        encoding="utf-8",
    )
    kmz = run(geo, "geo:kmz")
    geo_back = run(kmz, "geo:geojson")
    feature = read_geo(geo_back, "geojson")[0]
    if feature["geometry"]["coordinates"] != [126.978, 37.5665, 12.0] or feature[
        "properties"
    ] != {"name": "서울", "n": 42}:
        raise RuntimeError("WGS84 properties/coordinates failed")
    from magic_converter.core.conversion.file_router import slots_for

    for file, key in (
        (source, "data:yaml"),
        (font, "font:woff2"),
        (epub, "ebook:fb2"),
        (eml, "email:attachments"),
        (obj, "mesh:stl"),
        (geo, "geo:kmz"),
    ):
        if key not in {s.action.key for s in slots_for([file], "convert") if s.enabled}:
            raise RuntimeError("Wheel is missing a specialized action: " + key)
    return {
        "status": "passed",
        "data": "typed nesting, null, integer >2^53",
        "font": "cmap, glyphs, fvar, fsType, TTF/OTF/WOFF/WOFF2",
        "ebook": "2 chapters, metadata, image bytes, real DOCX table/picture",
        "mail": "Korean MIME, CID, inert HTML, exact original/attachment ZIP",
        "mesh": "OBJ→STL→PLY triangle coordinates",
        "geo": "WGS84 GeoJSON→KMZ→GeoJSON and typed attributes",
        "wheel": "all six families",
        "licenses": "7 original license texts with SHA-256 verified",
        "notices": len(notices),
    }
